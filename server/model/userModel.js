const mongoose = require("mongoose");

const UserSchema = new mongoose.Schema({
    username: {
        type: String,
        required: true,
        unique: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true,
    },
    role: {
        type: String,
        required: true,
        enum: ["root", "admin", "predajca"], default: "predajca"
    },
}, {collection: "Users"});

module.exports = mongoose.model("Users", UserSchema);